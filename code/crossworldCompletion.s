; FR: completion menu (OPT_COMPLETION), for a 100% game.
;
; Farore's secret list engine (code/crossworldSecretList.s), opened from the
; inventory with A on the heart pieces (wSubmenuState = FR_COMPLETION_MARK).
;
; - Summary: one row per category with "done/total" (heart pieces, heart
;   containers, essences, rings, trading sequence, secret exchanges) and the
;   completion percentage. The bottom box says "A = list", except on the
;   trading row: it tells where to get the next item.
; - A on a category: list of what is still missing (11 rows per page, < > to
;   change page, B to go back); the bottom box gives the map square, or the
;   dungeon level. A on the secrets row opens the secrets tracker.
;
; The data (names in the ROM's language) is generated by fr/make_completion.py
; in code/crossworldCompletionData.s. The mode is kept in wSecretListMenu.cbb4
; (0 = summary, k+1 = list of category k), cleared when the menu opens.

; FR_COMP_NO_SECRETS: separate games (no secret exchanges between the games, see
; ZeldaOracleCombinedFR/oracles-hud): no secrets row, no secrets tracker.
.ifdef FR_COMP_NO_SECRETS
.define FR_COMP_NUM_CATEGORIES	5
.else
.define FR_COMP_NUM_CATEGORIES	6
.define FR_COMP_CAT_SECRETS	5
.endif
.define FR_COMP_CAT_TRADE	4
.define FR_COMP_ROWS		11

;;
; @param[out]	zflag	z if the secret list was opened as the completion menu
frCompletion_isOpen:
	ld a,(wSubmenuState)
	cp FR_COMPLETION_MARK
	ret

;;
; Called by state 1 of the secret list before its own input.
; @param[out]	cflag	c if the input was used (the menu reloads)
frCompletion_input:
	ld a,(wKeysJustPressed)
	ld b,a
	ld a,(wSecretListMenu.cbb4)
	or a
	jr nz,@list

	; Summary: A opens the list of a category
	bit BTN_BIT_A,b
	ret z
	ld a,(wSecretListMenu.cursorIndex)
.ifdef FR_COMP_NO_SECRETS
	cp FR_COMP_NUM_CATEGORIES
.else
	cp FR_COMP_CAT_SECRETS
	jr z,@secrets
.endif
	ret nc
	inc a
	ld (wSecretListMenu.cbb4),a
	xor a
	jr @setPage

.ifndef FR_COMP_NO_SECRETS
@secrets:
	ld a,FR_TRACKER_MARK
	ld (wSubmenuState),a
	jr @reload
.endif

@list:
	; B: back to the summary
	bit BTN_BIT_B,b
	jr z,+
	xor a
	ld (wSecretListMenu.cbb4),a
	jr @reload
+
	ld a,(wFrCompPage)
	bit BTN_BIT_RIGHT,b
	jr nz,@right
	bit BTN_BIT_LEFT,b
	jr nz,@left
@ignore:
	xor a
	ret

@right:
	add FR_COMP_ROWS
	ld c,a
	ld a,(wFrCompDone) ; number of missing things
	cp c
	jr c,@ignore
	jr z,@ignore
	ld a,c
	jr @setPage
@left:
	sub FR_COMP_ROWS
	jr c,@ignore
@setPage:
	ld (wFrCompPage),a

@reload:
	; Back to state 0: the menu is drawn again
	xor a
	ld (wSecretListMenu.state),a
	ld (wSecretListMenu.cursorIndex),a
	ld (wSecretListMenu.scroll),a
	ld a,SND_MENU_MOVE
	call playSound
	scf
	ret

;;
; Loads the rows (summary or list) to vram.
; @param	de	Vram destination of the first row
frCompletion_loadRows:
	call frCompletion_prepare
	ld a,(wSecretListMenu.cbb4)
	or a
	jr nz,frCompletion_loadList

	xor a
	ld (wFrCompDone),a
	ld b,a
@nextCategory:
	push bc
	push de
	call frComp_clearBuffer
	pop de
	pop bc
	push bc
	push de
	ld a,b
	call frComp_writeLabel
	pop de
	pop bc
	push bc
	ld a,b
	call frComp_countCategory
	ld a,(wFrCompDone)
	add c
	ld (wFrCompDone),a

	; "done/total" at the end of the row
	ld hl,wFrCompRowBuffer+16
	ld a,b
	call frComp_writeNumberBackwards
	dec hl
	ld (hl),'/'
	ld a,c
	call frComp_writeNumberBackwards
	call frComp_copyBuffer
	pop bc
	inc b
	ld a,b
	cp FR_COMP_NUM_CATEGORIES
	jr c,@nextCategory

	; Total row: percentage
	push de
	call frComp_clearBuffer
	ld a,FR_COMP_NUM_CATEGORIES
	call frComp_writeLabel
	pop de
	call frComp_getPercent
	ld hl,wFrCompRowBuffer+15
	ld (hl),'%'
	call frComp_writeNumberBackwards
	call frComp_copyBuffer
	ld b,FR_COMP_NUM_CATEGORIES+1
	jp frSecretList_setNumEntries

;;
; List of the missing things of category (cbb4 - 1), from wFrCompPage.
; Counts all of them in wFrCompDone.
frCompletion_loadList:
	push de
	ld hl,wFrCompRowEntries
	ld b,FR_COMP_ROWS
	ld a,$ff
	call fillMemory
	ld a,(wSecretListMenu.cbb4)
	dec a
	call frComp_getCategory
	pop de
	xor a
	ld (wFrCompDone),a
	ld (wSecretListMenu.numEntries),a
	ld c,a

@nextEntry:
	push hl
	call frComp_entryDone
	jr nz,@skip

	; Missing: count it, show it if on this page
	ld a,(wFrCompDone)
	inc a
	ld (wFrCompDone),a
	dec a
	push hl
	ld hl,wFrCompPage
	cp (hl)
	pop hl
	jr c,@skip
	ld a,(wSecretListMenu.numEntries)
	cp FR_COMP_ROWS
	jr nc,@skip

	push hl
	ld hl,wFrCompRowEntries
	rst_addAToHl
	ld (hl),c
	ld hl,wSecretListMenu.numEntries
	inc (hl)
	pop hl

	ldi a,(hl)
	ld h,(hl)
	ld l,a
	push bc
	call frCopyTextCharactersUntilNull
	pop bc
	call frSecretList_nextRow
@skip:
	pop hl
	ld a,7
	rst_addAToHl
	inc c
	dec b
	jr nz,@nextEntry

	ld a,(wFrCompDone)
	or a
	ret nz
	ld hl,frCompAllDoneRow
	call frCopyTextCharactersUntilNull
	ld b,$01
	jp frSecretList_setNumEntries

;;
; Bottom box for row c.
frCompletion_printBox:
	ld a,$ff
	ld (wFileSelect.fontXor),a
	ld a,(wSecretListMenu.cbb4)
	or a
	jr nz,@list

	ld a,c
	cp FR_COMP_CAT_TRADE
	jr z,@nextTrade
	cp FR_COMP_NUM_CATEGORIES
	jr nc,@blank
	ld hl,frCompHintBox
	jr @copy

@nextTrade:
	; Where to get the next item of the trading sequence
	call frComp_getCategory
-
	push hl
	call frComp_entryDone
	jr z,@foundTrade
	pop hl
	ld a,7
	rst_addAToHl
	dec b
	jr nz,-
	jr @blank
@foundTrade:
	pop af
	inc hl
	inc hl
	jr @entryBox

@list:
	ld a,c
	ld hl,wFrCompRowEntries
	rst_addAToHl
	ld a,(hl)
	cp $ff
	jr z,@blank
	ld c,a
	ld a,(wSecretListMenu.cbb4)
	dec a
	call frComp_getCategory
	ld de,7
	inc c
-
	dec c
	jr z,+
	add hl,de
	jr -
+
	ld a,5
	rst_addAToHl
@entryBox:
	ldi a,(hl)
	ld h,(hl)
	ld l,a
	or h
	jr z,@pages
@copy:
	ld de,w7d800
	ld b,$c*2
	call frCopyTextCharacters
@blank:
	ld a,UNCMP_GFXH_35
	jp loadUncompressedGfxHeader

@pages:
	; No text for this entry: "< page/pages >" if there are several pages
	ld a,(wFrCompDone)
	cp FR_COMP_ROWS+1
	jr c,@blank
	ld hl,w7SecretText1
	ld b,$c*2
	ld a,' '
	call fillMemory
	ld hl,w7SecretText1+1
	ld (hl),'<'
	ld hl,w7SecretText1+9
	ld (hl),'>'
	ld a,(wFrCompDone)
	add FR_COMP_ROWS-1
	call frComp_divideBy11
	ld hl,w7SecretText1+8
	call frComp_writeNumberBackwards
	dec hl
	ld (hl),'/'
	ld a,(wFrCompPage)
	call frComp_divideBy11
	inc a
	call frComp_writeNumberBackwards
	ld hl,w7SecretText1
	jr @copy

;;
; Computes the trading sequence and secret exchange bits (wFrCompTrade,
; wFrCompSecrets) read by the data entries.
frCompletion_prepare:
.ifndef FR_COMP_NO_SECRETS
	; Secret exchanges: bit i = exchange i complete
	xor a
	ld hl,wFrCompSecrets
	ldi (hl),a
	ld (hl),a
	ld c,a
@nextSecret:
	push bc
	call frTracker_getStatus
	pop bc
	cp $03
	jr nz,+
	ld a,c
	ld hl,wFrCompSecrets
	call setFlag
+
	inc c
	ld a,c
	cp $0a
	jr c,@nextSecret
.endif

	; Noble sword (bit 12)
.ifdef ROM_AGES
	ld a,GLOBALFLAG_PATCH_REPAIRED_EVERYTHING
	call checkGlobalFlag
	ld b,$00
	jr z,+
	inc b
+
.else
	; Lost Woods (any noble or master sword counts)
	ld a,(wSwordLevel)
	cp $02
	ld b,$00
	jr c,+
	inc b
+
.endif

	; Items obtained: while an item is held, all up to wTradeItem; once the
	; last one is given away (item no longer held, wTradeItem not 0), all 12.
	ld a,(wTradeItem)
	ld c,a
	ld a,(wObtainedTreasureFlags + TREASURE_TRADEITEM/8)
	and 1 << (TREASURE_TRADEITEM & 7)
	jr z,+
	inc c
	jr ++
+
	ld a,c
	or a
	jr z,++
	ld c,12
++
	ld a,c
	cp 13
	jr c,+
	ld c,12
+
	ld hl,$0000
	inc c
	jr @shift
-
	add hl,hl
	inc l
@shift:
	dec c
	jr nz,-

	ld a,b
	or a
	jr z,+
	set 4,h
+
	ld a,l
	ld (wFrCompTrade),a
	ld a,h
	ld (wFrCompTrade+1),a
	ret

;;
; @param	a	Category
; @param[out]	b	Number of entries
; @param[out]	hl	First entry
frComp_getCategory:
	push de
	ld e,a
	add a
	add e
	ld hl,frCompCategories
	rst_addAToHl
	ldi a,(hl)
	ld e,a
	ldi a,(hl)
	ld d,a
	ld b,(hl)
	ld h,d
	ld l,e
	pop de
	ret

;;
; @param	hl	Entry
; @param[out]	hl	Entry + 3 (row text)
; @param[out]	zflag	nz if done
frComp_entryDone:
	push de
	ldi a,(hl)
	ld e,a
	ldi a,(hl)
	ld d,a
	ld a,(de)
	and (hl)
	inc hl
	pop de
	ret

;;
; @param	a	Category
; @param[out]	b	Total
; @param[out]	c	Done
frComp_countCategory:
	push de
	call frComp_getCategory
	ld d,b
	ld c,$00
-
	call frComp_entryDone
	jr z,+
	inc c
+
	ld a,4
	rst_addAToHl
	dec d
	jr nz,-
	pop de
	ret

;;
; @param[out]	a	wFrCompDone * 100 / total of all categories
frComp_getPercent:
	push de
	ld e,$00
	ld c,FR_COMP_NUM_CATEGORIES
-
	dec c
	ld a,c
	call frComp_getCategory
	ld a,e
	add b
	ld e,a
	ld a,c
	or a
	jr nz,-
	ld d,a

	; hl = done * 100 (64 + 32 + 4)
	ld a,(wFrCompDone)
	ld l,a
	ld h,$00
	add hl,hl
	add hl,hl
	push hl
	add hl,hl
	add hl,hl
	add hl,hl
	push hl
	add hl,hl
	pop bc
	add hl,bc
	pop bc
	add hl,bc

	ld c,$ff
-
	inc c
	ld a,l
	sub e
	ld l,a
	ld a,h
	sbc d
	ld h,a
	jr nc,-
	ld a,c
	pop de
	ret

;;
; @param	a	Value
; @param[out]	a	Value / 11
frComp_divideBy11:
	ld c,$ff
-
	inc c
	sub FR_COMP_ROWS
	jr nc,-
	ld a,c
	ret

;;
; @param	a	Number (0-255)
; @param	hl	Address after the last digit
; @param[out]	hl	Address of the first digit
frComp_writeNumberBackwards:
	push bc
-
	ld b,$ff
--
	inc b
	sub 10
	jr nc,--
	add 10+'0'
	dec hl
	ld (hl),a
	ld a,b
	or a
	jr nz,-
	pop bc
	ret

;;
frComp_clearBuffer:
	ld hl,wFrCompRowBuffer
	ld b,16
	ld a,' '
	jp fillMemory

;;
; @param	a	Label index (frCompLabels)
frComp_writeLabel:
	ld hl,frCompLabels
	rst_addDoubleIndex
	ldi a,(hl)
	ld h,(hl)
	ld l,a
	ld de,wFrCompRowBuffer
-
	ldi a,(hl)
	or a
	ret z
	ld (de),a
	inc de
	jr -

;;
; @param	de	Vram destination; next row on return
frComp_copyBuffer:
	push bc
	ld hl,wFrCompRowBuffer
	ld b,16
	call frCopyTextCharacters
	pop bc
	jp frSecretList_nextRow
